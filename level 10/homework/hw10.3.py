
# შექმენით პროგრამა, რომელშიც მომხმარებელმა უნდა გამოიცნოს წინასწარ განსაზღვრული რიცხვი (მაგალითად, 42). გამოიყენეთ while ციკლი, რათა მომხმარებელს ჰქონდეს გამოცნობის რამდენიმე მცდელობა. თუ შეყვანილი რიცხვი საიდუმლო რიცხვზე მეტია ან ნაკლებია, გამოიტანეთ შესაბამისი შეტყობინება. სწორი პასუხის შემთხვევაში გამოიტანეთ გამარჯვების შეტყობინება და მცდელობების რაოდენობა.





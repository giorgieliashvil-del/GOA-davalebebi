# თქვენი დავალებაა შექმნათ 4 ფუნქცია: add, subtruct, multiply და divide, თითოეულ მათგანს უნდა გადაეცემოდეს არგუმენტად ორი რიცხვი და თითოეულმა ფუნქციამ უნდა ჩაატაროს შესაბამისი მათემატიკური ოპერაცია (დამატება, გამოკლება, გამრავლება და გაყოფა), თითოეული ფუნქცია უნდა აბრუნებდეს მიღებულ შედეგს, საბოლოოდ გამოიყენეთ ოთხივე ფუნქცია და ტერმინალში გამოიტანეთ მათემატიკური ოპერაციების შედეგები.

def add(number1, number2):
    return number1 + number2

def subtruct(number1, number2):
    return number1 - number2

def multiply(number1, number2):
    return number1 * number2

def divide(number1, number2):
    return number1 / number2

print(add(10, 20))
print(subtruct(100, 32))
print(multiply(10, 3))
print(divide(100, 4))
